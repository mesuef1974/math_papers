/** يقسم نصًا على علامة ` فيعيد مقاطع، المقطع الفردي (بعد علامة) شيفرة. */
export function splitCode(text: string): { text: string; code: boolean }[] {
  return text
    .split("`")
    .map((part, index) => ({ text: part, code: index % 2 === 1 }))
    .filter((part) => part.text !== "");
}

export function statusCounts(stages: Stage[] = STAGES): Record<StageStatus, number> {
  const out: Record<StageStatus, number> = { done: 0, run: 0, plan: 0 };
  for (const stage of stages) out[stage.status] += 1;
  return out;
}
